// Factory wavetables are generated on demand: size per table, thread-safe generation, control-thread preload on
// parameter changes and the preload switch of EngineConfig.

#include <crucible/Engine.h>
#include <crucible/crucible.h>
#include <crucible/Spectral.h>
#include <crucible/SynthEngine.h>
#include <crucible/Wavetables.h>
#include "AllocCounter.h"
#include "TestSupport.h"

#include <thread>

using namespace crucible;
using namespace crucible::testing;

class WavetableMemoryTests : public UnitTest
{
public:
    WavetableMemoryTests() : UnitTest("Wavetable memory", "Engine") {}

    void runTest() override
    {
        const auto& bank = WavetableBank::instance();

        beginTest("the tables the oscillators start on are generated by prepare, so the first process() allocates nothing");
        {
            // Runs first on purpose: the default table is not resident yet when this suite is run alone.
            std::vector<float> l(256), r(256);
            {
                Engine e;
                e.prepare(kRate, 512);
                const int table =
                    static_cast<int>(e.model().params()[static_cast<size_t>(e.model().indexOf("osc1_table"))].defaultValue);
                expect(bank.resident(table), "the default table is resident after prepare");
                expect(spectral::FactoryTables::instance().get(table) != nullptr,
                       "its spectral table is ready after prepare");
                e.noteOn(60, 0.9f);
                crucible::testing::gAllocations = 0;
                crucible::testing::gTrackAllocations = true;
                e.process(l.data(), r.data(), 256);
                crucible::testing::gTrackAllocations = false;
                expectEquals(static_cast<int>(crucible::testing::gAllocations), 0, "Engine first process allocations");
                float peak = 0.0f;
                for (const float v : l)
                    peak = std::max(peak, std::abs(v));
                expect(peak > 0.0f, "the first block sounds");
            }
            {
                SynthEngine synth;
                synth.prepare(kRate);
                const std::vector<float> values = synth.model().defaultValues();
                synth.noteOn(60, 0.9f);
                crucible::testing::gAllocations = 0;
                crucible::testing::gTrackAllocations = true;
                synth.setParameterValues(values.data(), static_cast<int>(values.size()));
                synth.render(l.data(), r.data(), 256);
                crucible::testing::gTrackAllocations = false;
                expectEquals(static_cast<int>(crucible::testing::gAllocations), 0, "SynthEngine first call allocations");
                float peak = 0.0f;
                for (const float v : l)
                    peak = std::max(peak, std::abs(v));
                expect(peak > 0.0f, "the first block sounds");
            }
        }

        beginTest("a table takes about 9 MB and all fourteen stay below 130 MB");
        {
            const double mb = static_cast<double>(WavetableBank::bytesPerTable()) / (1024.0 * 1024.0);
            expect(mb > 8.0 && mb < 9.5, "per table " + std::to_string(mb));
            expect(mb * WavetableBank::numTables < 130.0, "all tables " + std::to_string(mb * WavetableBank::numTables));
        }

        beginTest("concurrent first use generates a table once and every caller sees the same complete data");
        {
            const int table = WavetableBank::numTables - 1;
            std::vector<const float*> seen(4, nullptr);
            std::vector<float> peak(4, 0.0f);
            std::vector<std::thread> threads;
            for (size_t i = 0; i < seen.size(); ++i)
                threads.emplace_back(
                    [&, i]
                    {
                        seen[i] = bank.frame(table, 3, 10);
                        for (int s = 0; s < WavetableBank::mipSize(3); ++s)
                            peak[i] = std::max(peak[i], std::abs(seen[i][s]));
                    });
            for (auto& t : threads)
                t.join();
            expect(bank.resident(table));
            for (size_t i = 1; i < seen.size(); ++i)
                expect(seen[i] == seen[0] && peak[i] == peak[0]);
            expect(peak[0] > 0.1f && peak[0] < 1.3f, "peak " + std::to_string(peak[0]));
            const auto before = bank.residentBytes();
            bank.ensure(table);
            expectEquals(static_cast<double>(bank.residentBytes()), static_cast<double>(before));
            expect(bank.frame(table, 3, 10) == seen[0], "pointers stay put");
        }

        beginTest("pointing an oscillator at a table generates it on the calling thread");
        {
            Engine e;
            e.prepare(kRate, 512);
            expect(bank.resident(0));
            e.setParam("osc3_table", 4.0f);
            expect(bank.resident(4));
            e.setParam("osc2_table", 9.0f);
            expect(bank.resident(9));
            // Out-of-range values (user tables) are ignored by the factory bank.
            expect(e.setParam("osc1_table", static_cast<float>(WavetableBank::numTables)));
            bank.ensure(-1);
            bank.ensure(WavetableBank::numTables + 3);
        }

        beginTest("a table switched with setParamRt before service() is not generated on the audio thread");
        {
            int fresh = -1;
            for (int t = 0; t < WavetableBank::numTables && fresh < 0; ++t)
                if (!bank.resident(t))
                    fresh = t;
            Engine e;
            e.prepare(kRate, 512);
            const int idx = e.model().indexOf("osc1_table");
            e.noteOn(60, 0.9f);
            std::vector<float> l(256), r(256);
            for (int i = 0; i < 4; ++i)
                e.process(l.data(), r.data(), 256);
            if (fresh >= 0)
            {
                expect(e.setParamRt(idx, static_cast<float>(fresh)));
                crucible::testing::gAllocations = 0;
                crucible::testing::gTrackAllocations = true;
                for (int i = 0; i < 4; ++i)
                    e.process(l.data(), r.data(), 256);
                crucible::testing::gTrackAllocations = false;
                expectEquals(static_cast<int>(crucible::testing::gAllocations), 0, "allocations");
                expect(!bank.resident(fresh), "the audio thread must not generate the table");
                e.service();
                expect(bank.resident(fresh));
                float peak = 0.0f;
                for (int i = 0; i < 8; ++i)
                {
                    e.process(l.data(), r.data(), 256);
                    for (const float v : l)
                        peak = std::max(peak, std::abs(v));
                }
                expect(peak > 0.001f, "the table sounds after service(), peak " + std::to_string(peak));
            }
        }

        beginTest("the first crucible_process_events selecting an ungenerated table allocates nothing; the table sounds "
                  "after crucible_service");
        {
            int fresh = -1;
            for (int t = WavetableBank::numTables - 1; t >= 0 && fresh < 0; --t)
                if (!bank.resident(t))
                    fresh = t;
            if (fresh >= 0)
            {
                CrucibleConfig config{};
                config.struct_size = sizeof(config);
                CrucibleEngine* ce = crucible_create(&config);
                expect(ce != nullptr);
                if (ce != nullptr)
                {
                    crucible_prepare(ce, 48000.0, 512);
                    const int idx = crucible_param_index(ce, "osc1_table");
                    std::vector<float> l(512), r(512);
                    const CrucibleMidiEvent note[1] = {{0, 0x90, 60, 100}};
                    const CrucibleParamEvent change[1] = {{0, idx, static_cast<float>(fresh)}};
                    crucible::testing::gAllocations = 0;
                    crucible::testing::gTrackAllocations = true;
                    crucible_process_events(ce, l.data(), r.data(), 512, note, 1, change, 1, nullptr);
                    crucible::testing::gTrackAllocations = false;
                    expectEquals(static_cast<int>(crucible::testing::gAllocations), 0, "first block allocations");
                    expect(!bank.resident(fresh), "the audio thread must not generate the table");
                    crucible_service(ce);
                    expect(bank.resident(fresh), "service generates it");
                    float peak = 0.0f;
                    for (int i = 0; i < 8; ++i)
                    {
                        crucible_process_events(ce, l.data(), r.data(), 512, nullptr, 0, nullptr, 0, nullptr);
                        for (const float v : l)
                            peak = std::max(peak, std::abs(v));
                    }
                    expect(peak > 0.001f, "the table sounds after service, peak " + std::to_string(peak));
                    crucible_destroy(ce);
                }
            }
        }

        beginTest("preloadWavetables generates every table with the engine");
        {
            EngineConfig config;
            config.preloadWavetables = true;
            Engine e(config);
            for (int t = 0; t < WavetableBank::numTables; ++t)
                expect(bank.resident(t), "table " + std::to_string(t));
            expect(static_cast<double>(bank.residentBytes()) / (1024.0 * 1024.0) < 130.0);
        }
    }
};

static WavetableMemoryTests wavetableMemoryTests;
